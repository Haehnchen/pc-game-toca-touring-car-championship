#pragma once

#include "simulation/source_scene_frame.hpp"

#include <bit>
#include <fstream>
#include <stdexcept>
#include <string_view>

namespace toca::scene_test {
using namespace toca::scene;

class Output {
    std::ofstream file_;
    std::ostream* output_;

public:
    explicit Output(const char* path) : file_(path), output_(&file_) {
        file_.exceptions(std::ios::failbit | std::ios::badbit);
        *output_ << "order,group,index,field,value\n";
    }

    explicit Output(std::ostream& output) : output_(&output) {}

    void row(std::uint64_t order, std::string_view group, std::uint32_t index, std::string_view field, std::int64_t value) {
        *output_ << order << ',' << group << ',' << index << ',' << field << ',' << value << '\n';
    }

    void registration(std::uint64_t order, std::uint32_t root, const SceneFrameJournal& journal, bool neighbors) {
        const auto registration = journal.root_registration(root);
        row(order, "root", root, "sector", registration.sector);
        if (neighbors) {
            for (std::uint32_t axis = 0; axis < 3; ++axis) {
                row(order, "root", root, "neighbor_" + std::to_string(axis), registration.neighbors[axis]);
            }
        }
    }

    void pvs(std::uint64_t order, const VisibilityFrame& selected) {
        row(order, "pvs", 0, "count", selected.ordered_sectors.size());
        for (std::uint32_t index = 0; index < selected.ordered_sectors.size(); ++index) {
            row(order, "pvs", index, "order", selected.ordered_sectors[index]);
        }
        std::array<std::uint8_t, 256> bits{};
        if (selected.detail.size() > bits.size() * 8) {
            throw std::runtime_error("Scene visibility exceeds source bitmap");
        }
        for (std::uint32_t sector = 0; sector < selected.detail.size(); ++sector) {
            row(order, "pvs", sector, "detail", selected.detail[sector]);
            if (selected.selected[sector]) {
                bits[sector / 8] |= std::uint8_t(1u << (sector % 8));
            }
        }
        for (std::uint32_t index = 0; index < bits.size(); ++index) {
            row(order, "pvs", index, "bits", bits[index]);
        }
    }

    void models(std::uint64_t order, const SceneFrameJournal& journal, std::string_view group = "models") {
        // Canonical .data adeb8=1 is generated by the shared model owner.
        row(order, group, 0, "refresh_request", 1);
        const auto& masks = journal.car_masks();
        constexpr std::array names{"high_manual", "medium_manual", "low_manual"};
        for (std::uint32_t actor = 0; actor < 16; ++actor) {
            const auto detail = journal.model_detail(actor);
            for (std::uint32_t level = 0; level < 3; ++level) {
                row(order, group, actor, names[level], masks[actor].car && detail == level);
            }
            row(order, group, actor, "car_mask", masks[actor].car);
            row(order, group, actor, "high_medium_mask", masks[actor].high_medium);
            row(order, group, actor, "full_body_mask", masks[actor].full);
        }
    }
};

inline void write_initial_roots(std::ostream& stream, const simulation::SourceSceneFrame& frames, const std::array<GridSlot, 32>& grid, bool include_cockpit = false) {
    Output output(stream);
    const auto roots = simulation::source_scene_roots(grid);
    constexpr std::array fields{"position_x_bits", "position_y_bits", "position_z_bits"};
    for (std::uint32_t root = 0; root < (include_cockpit ? roots.size() : 17); ++root) {
        for (std::uint32_t axis = 0; axis < 3; ++axis) {
            output.row(0, "initial_roots", root, fields[axis], std::bit_cast<std::uint32_t>(roots[root].local_position[axis]));
        }
        output.row(0, "initial_roots", root, "sector", frames.scene().root_registration(root).sector);
    }
}

inline void write_frame(
    Output& output, std::uint32_t frame, const simulation::SourceSceneFrame& frames, const simulation::TimeStep& used, const simulation::TimeStep& next, bool controls = false) {
    output.row(frame, "timing", 0, "delta_q16", used.delta_q16);
    output.row(frame, "timing", 0, "reciprocal_q16", used.reciprocal_q16);
    output.row(frame, "timing", 0, "extra_update", used.extra_step);
    output.row(frame, "timing", 0, "physical_count", used.update_count());
    if (controls) {
        const auto& state = frames.published_state();
        output.row(frame, "control", 0, "selected_view", state.view);
        output.row(frame, "control", 0, "projection_view", state.projection_view);
        output.row(frame, "control", 0, "rear_held", state.rear_held);
        output.row(frame, "control", 0, "ancestor_root", state.ancestor_root);
    }
    const auto& camera = frames.camera();
    for (std::uint32_t index = 0; index < 16; ++index) {
        output.row(frame, "camera", index, "world_bits", std::bit_cast<std::uint32_t>(camera.camera_to_world[index]));
    }
    for (std::uint32_t index = 0; index < 16; ++index) {
        output.row(frame, "camera", index, "view_bits", std::bit_cast<std::uint32_t>(camera.world_to_view[index]));
    }
    for (std::uint32_t index = 0; index < 3; ++index) {
        output.row(frame, "camera", index, "position_bits", std::bit_cast<std::uint32_t>(camera.world_position[index]));
    }
    std::array<std::int32_t, 16> projection{};
    const auto& p = frames.projection();
    projection[0] = std::int32_t(p.x * 65536.f);
    projection[5] = std::int32_t(p.y * 65536.f);
    projection[10] = std::int32_t(p.depth_scale * 65536.f);
    projection[11] = 65536;
    projection[14] = std::int32_t(p.depth_offset * 65536.f);
    for (std::uint32_t index = 0; index < 16; ++index) {
        output.row(frame, "projection", index, "q16", projection[index]);
    }
    const auto& journal = frames.scene();
    output.pvs(frame, journal.visibility());
    output.models(frame, journal);
    output.models(frame, journal, "published_models");
    for (std::uint32_t actor = 0; actor < 16; ++actor) {
        const auto root = frames.car_root(actor);
        output.registration(frame, root, journal, true);
        output.row(frame, "root", root, "render_mask", journal.visibility().root_mask(root) & 1);
        output.row(frame, "root", root, "manual_mask", journal.root_manual_mask(root) & 1);
    }
    output.row(frame, "next_timing", 0, "delta_q16", next.delta_q16);
    output.row(frame, "next_timing", 0, "reciprocal_q16", next.reciprocal_q16);
    output.row(frame, "next_timing", 0, "extra_update", next.extra_step);
}

inline void write_frame(std::ostream& stream, std::uint32_t frame, const simulation::SourceSceneFrame& frames, const simulation::TimeStep& used, const simulation::TimeStep& next,
    bool controls = false) {
    Output output(stream);
    write_frame(output, frame, frames, used, next, controls);
}

inline void write_lifecycle_pre(Output& output, std::uint32_t id, const simulation::SourceSceneFrame& frames) {
    const auto& journal = frames.scene();
    const auto& context = frames.retained_context();
    const auto& selected = journal.visibility();
    for (std::uint32_t actor = 0; actor < 16; ++actor) {
        const auto root = frames.car_root(actor);
        const auto& registration = context.actors[actor].physical;
        output.row(id, "pre_root", actor, "sector", registration.sector);
        for (std::uint32_t neighbor = 0; neighbor < 3; ++neighbor) {
            output.row(id, "pre_root", actor, "neighbor_" + std::to_string(neighbor), registration.neighbors[neighbor]);
        }
        output.row(id, "pre_root", actor, "render_mask", context.actors[actor].render_mask & 1);
        output.row(id, "pre_root", actor, "manual_mask", journal.root_manual_mask(root) & 1);
        output.row(id, "pre_root", actor, "effect_mask", context.actors[actor].contact_effect_mask & 1);
        output.row(id, "pre_root", actor, "sector_visible", context.actors[actor].sector_visible);
    }
    std::array<std::uint8_t, 256> bits{};
    for (std::uint32_t sector = 0; sector < selected.selected.size(); ++sector) {
        if (selected.selected[sector]) {
            bits[sector / 8] |= std::uint8_t(1u << (sector % 8));
        }
    }
    for (std::uint32_t index = 0; index < bits.size(); ++index) {
        output.row(id, "pre_pvs", index, "bits", bits[index]);
    }
    output.row(id, "pre_scene", 0, "selected_count", selected.ordered_sectors.size());
    output.row(id, "pre_scene", 0, "all_sectors", selected.all_sectors);
}

inline void write_lifecycle_pre(std::ostream& stream, std::uint32_t id, const simulation::SourceSceneFrame& frames) {
    Output output(stream);
    write_lifecycle_pre(output, id, frames);
}

inline void write_lifecycle_wheels(std::ostream& stream, std::uint32_t id, std::uint32_t call, const simulation::SourceSceneFrame& frames) {
    Output output(stream);
    for (std::uint32_t actor = 0; actor < 16; ++actor) {
        output.row(id, "wheel_full", call * 16 + actor, "mask", frames.car_masks()[actor].full);
    }
}

} // namespace toca::scene_test
